-- 🛵 مناديب الدفع المقدم — تحديث 3
--   1) حالة جديدة "🛵 مع المندوب" (out) — الأوردر الجديد بيبدأ ⏳ لسه (pending)
--   2) خانة ملاحظات المندوب (courier_note) — المندوب يكتب فيها اللي حصل
--   3) 💰 حسابات المناديب: جدول prepaid_advances — المندوب دفع كام مقدم ولأنهي أوردرات
-- شغّله مرة واحدة في Supabase → SQL Editor (بعد prepaid_orders.sql و prepaid_orders_2.sql). مش بيلغي أي حاجة موجودة.

-- 1) الحالات: pending (لسه) · out (مع المندوب) · delivered (اتسلم) · failed (ماتسلمش)
alter table public.prepaid_orders drop constraint if exists prepaid_orders_status_check;
alter table public.prepaid_orders add constraint prepaid_orders_status_check check (status in ('pending','out','delivered','failed'));

-- 2) ملاحظات المندوب
alter table public.prepaid_orders add column if not exists courier_note text;
alter table public.prepaid_orders add column if not exists courier_note_at timestamptz;
alter table public.prepaid_orders add column if not exists courier_note_by text;

create or replace function public.prepaid_set_status(p_id bigint, p_status text, p_note text default null) returns boolean
language plpgsql security definer set search_path = public as $$
declare n int; nm text; is_c boolean;
begin
  if p_status not in ('pending','out','delivered','failed') then raise exception 'bad status'; end if;
  select coalesce(full_name, username), coalesce(to_jsonb(allowed_sections) ? 'prepaid', false) into nm, is_c from public.profiles where id = auth.uid();
  update public.prepaid_orders set
    status = p_status,
    status_note = case when p_status in ('pending','out') then null else nullif(trim(coalesce(p_note, '')), '') end,
    status_at = case when p_status = 'pending' then null else now() end,
    status_by_name = case when p_status = 'pending' then null else nm end,
    courier_id = coalesce(courier_id, case when is_c then auth.uid() end),
    courier_name = coalesce(courier_name, case when is_c then nm end)
  where id = p_id and (courier_id = auth.uid() or public.app_has_section('prepaid') or public.app_has_section('prepaid_admin'));
  get diagnostics n = row_count;
  return n > 0;
end $$;

-- تغيير حالة كذا أوردر مرة واحدة (مثلاً: علّم 10 أوردرات "مع المندوب")
create or replace function public.prepaid_set_status_many(p_ids bigint[], p_status text) returns int
language plpgsql security definer set search_path = public as $$
declare n int; nm text; is_c boolean;
begin
  if p_status not in ('pending','out','delivered','failed') then raise exception 'bad status'; end if;
  select coalesce(full_name, username), coalesce(to_jsonb(allowed_sections) ? 'prepaid', false) into nm, is_c from public.profiles where id = auth.uid();
  update public.prepaid_orders set
    status = p_status,
    status_note = case when p_status in ('pending','out') then null else status_note end,
    status_at = case when p_status = 'pending' then null else now() end,
    status_by_name = case when p_status = 'pending' then null else nm end,
    courier_id = coalesce(courier_id, case when is_c then auth.uid() end),
    courier_name = coalesce(courier_name, case when is_c then nm end)
  where id = any(p_ids) and (courier_id = auth.uid() or public.app_has_section('prepaid') or public.app_has_section('prepaid_admin'));
  get diagnostics n = row_count;
  return n;
end $$;

-- المندوب يكتب ملاحظة على الأوردر (من غير ما يعدّل أي بيانات تانية)
create or replace function public.prepaid_set_note(p_id bigint, p_note text) returns boolean
language plpgsql security definer set search_path = public as $$
declare n int; nm text;
begin
  select coalesce(full_name, username) into nm from public.profiles where id = auth.uid();
  update public.prepaid_orders set
    courier_note = nullif(trim(coalesce(p_note, '')), ''),
    courier_note_at = case when nullif(trim(coalesce(p_note, '')), '') is null then null else now() end,
    courier_note_by = case when nullif(trim(coalesce(p_note, '')), '') is null then null else nm end
  where id = p_id and (courier_id = auth.uid() or public.app_has_section('prepaid') or public.app_has_section('prepaid_admin'));
  get diagnostics n = row_count;
  return n > 0;
end $$;

grant execute on function public.prepaid_set_status(bigint, text, text) to authenticated;
grant execute on function public.prepaid_set_status_many(bigint[], text) to authenticated;
grant execute on function public.prepaid_set_note(bigint, text) to authenticated;

-- 3) 💰 حسابات المناديب: كل دفعة مقدم = مبلغ + الأوردرات اللي اتدفع عشانها
--    الحساب: المدفوع − قيمة اللي اتسلم = الباقي للمندوب (مرتجع / لسه معاه)
create table if not exists public.prepaid_advances (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  pay_date date not null default current_date,
  courier_id uuid,
  courier_name text,
  amount numeric not null default 0,
  order_ids bigint[] not null default '{}',
  note text,
  settled boolean not null default false,
  settled_at timestamptz,
  settled_by_name text,
  settle_note text,
  created_by uuid,
  created_by_name text
);
create index if not exists prepaid_advances_date_idx on public.prepaid_advances(pay_date desc);
create index if not exists prepaid_advances_courier_idx on public.prepaid_advances(courier_id);

alter table public.prepaid_advances enable row level security;
drop policy if exists "prepaid_adv: read"   on public.prepaid_advances;
drop policy if exists "prepaid_adv: insert" on public.prepaid_advances;
drop policy if exists "prepaid_adv: update" on public.prepaid_advances;
drop policy if exists "prepaid_adv: delete" on public.prepaid_advances;
-- المندوب يشوف حسابه — والمتابعين يشوفوا الكل
create policy "prepaid_adv: read" on public.prepaid_advances for select to authenticated
  using (courier_id = auth.uid() or public.app_has_section('prepaid') or public.app_has_section('prepaid_admin'));
-- تسجيل / تعديل / مسح الدفعات: للمتابعين (أدمن أو "متابعة كل المناديب") بس
create policy "prepaid_adv: insert" on public.prepaid_advances for insert to authenticated
  with check (public.app_has_section('prepaid_admin'));
create policy "prepaid_adv: update" on public.prepaid_advances for update to authenticated
  using (public.app_has_section('prepaid_admin')) with check (public.app_has_section('prepaid_admin'));
create policy "prepaid_adv: delete" on public.prepaid_advances for delete to authenticated
  using (public.app_has_section('prepaid_admin'));
grant select, insert, update, delete on public.prepaid_advances to authenticated;
